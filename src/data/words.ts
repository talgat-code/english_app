export type WordDifficulty = 'easy' | 'medium' | 'hard'

export interface Word {
  id: string
  english: string
  russian: string
  transcription: string
  example: string
  exampleRu: string
  difficulty: WordDifficulty
}

export interface Category {
  id: string
  title: string
  emoji: string
  words: Word[]
}

type WordEntry = [
  english: string,
  russian: string,
  transcription: string,
  example: string,
  exampleRu: string,
]

function difficultyByIndex(index: number, total: number): WordDifficulty {
  if (index < Math.ceil(total / 3)) return 'easy'
  if (index < Math.ceil((total * 2) / 3)) return 'medium'
  return 'hard'
}

function makeWords(prefix: string, entries: WordEntry[]): Word[] {
  return entries.map(([english, russian, transcription, example, exampleRu], index) => ({
    id: `${prefix}-${index + 1}`,
    english,
    russian,
    transcription,
    example,
    exampleRu,
    difficulty: difficultyByIndex(index, entries.length),
  }))
}

